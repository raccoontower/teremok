-- Из чьего кармана ушла выплата партнёру.
--
-- Продолжение 0009. После того как приход научился записываться на человека,
-- расчёт сошёлся не до конца: осталась разница ровно в размер выплаты. Причина
-- та же по своей природе — модель считала, что выплата уходит «со счёта фирмы»,
-- а общего счёта нет: один партнёр перевёл другому со своей карты.
--
-- Выплата — это перемещение денег между двумя людьми. У получателя она уже
-- учтена (`partner_id`), у плательщика не учитывалась никак, и его вклад в
-- общее дело оказывался занижен ровно на эту сумму.
--
-- Существующие строки записываются на владельца: все расходы в базе оплачены
-- с его карты, выплаты шли оттуда же. Если какая-то выплата была не от него —
-- поправить вручную, это одна строка.
--
-- Применять ВРУЧНУЮ в Supabase SQL Editor. Безопасно повторять.

alter table partner_payouts add column if not exists paid_by uuid references partners(id);

update partner_payouts
   set paid_by = (select id from partners where is_owner order by id limit 1)
 where paid_by is null;

comment on column partner_payouts.paid_by is
  'Партнёр, со счёта которого ушли деньги. Идёт ему в плюс при расчёте, как оплаченный из кармана расход.';
