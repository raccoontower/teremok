-- Партнёры тоже выходят на объекты, и их надо ставить в расписание. Но их
-- деньги — это доля в прибыли, а не зарплата: если считать им дневной рейт,
-- он вычтется из прибыли, а половину этой же прибыли они получат ещё раз.
-- Поэтому флаг: в расписании участвуют, в зарплату не попадают.
alter table workers add column is_partner boolean not null default false;
