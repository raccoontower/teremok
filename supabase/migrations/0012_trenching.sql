-- Раскопки на объекте оплачиваются по погонному футу, и это отдельная
-- позиция в договоре: «начальная цена за объект плюс длина траншеи на
-- ставку за фут». Хранить одну сумму мало — владельцу нужно показывать
-- управляющей компании, из чего она сложилась, а длину траншеи уточняют
-- уже после начала работ.
alter table sites add column trench_feet numeric(10,2);
alter table sites add column trench_rate numeric(10,2);

comment on column sites.contract_amount is 'Базовая цена за объект без раскопок';
comment on column sites.trench_feet is 'Длина раскопок в погонных футах';
comment on column sites.trench_rate is 'Цена за погонный фут раскопок';

-- Ставка почти всегда одна и та же — $15 за фут (решение владельца
-- 18.09.2026). Ставим значением по умолчанию, чтобы на объекте оставалось
-- ввести только длину. Где ставка другая, она просто перезаписывается.
alter table sites alter column trench_rate set default 15;
