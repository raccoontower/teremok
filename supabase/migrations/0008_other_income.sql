-- Доход не от объекта: прошлая работа, другой работодатель, разовая подработка.
--
-- До сих пор приход был возможен только по объекту (`income.site_id not null`):
-- модель исходила из того, что деньги приходят только от управляющей компании
-- за конкретную стройку. Но владелец ведёт здесь все свои финансы, а деньги
-- приходят и за работу, которой в системе нет и не будет — например расчёт от
-- прежнего работодателя. Такой приход некуда было записать, и месячная
-- прибыль получалась заниженной.
--
-- Объект становится необязательным, и появляется `source` — от кого пришло.
-- Для дохода по объекту источник и так понятен из объекта; для дохода без
-- объекта он единственное, что отличает одну строку от другой.
--
-- Применять ВРУЧНУЮ в Supabase SQL Editor. Безопасно повторять.
-- До применения приложение работает как раньше: приход без объекта просто
-- не сохранится, всё остальное не затрагивается.

alter table income alter column site_id drop not null;
alter table income add column if not exists source text;

