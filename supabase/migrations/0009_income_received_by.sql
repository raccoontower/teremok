-- Кто получил приход.
--
-- У расхода есть `paid_by`, у зарплаты `paid_by`, у выплаты партнёру
-- `partner_id` — всё, что уходит, записано на человека. А приход записан «на
-- фирму», которой как кошелька не существует: деньги физически кто-то получил.
--
-- Из-за этого расчёт с партнёром не сходился. 15 сентября: одному должны
-- $3 242, другой должен $3 042 — при делёже на двоих такого быть не может.
-- Разница $200 оказалась ровно «доход $1 200 минус выплата $1 000»: приход
-- повис между партнёрами, не записанный ни на кого. Пока это $200, дальше
-- разойдётся молча и сильнее.
--
-- NULL означает «пришло на общий счёт, ни на кого лично» — так остаётся
-- поведение для приходов от управляющей компании, которые на партнёра не
-- записывают.
--
-- Применять ВРУЧНУЮ в Supabase SQL Editor. Безопасно повторять.

alter table income add column if not exists received_by uuid references partners(id);

comment on column income.received_by is
  'Партнёр, физически получивший деньги. NULL — на общий счёт. Учитывается в расчёте делёжа.';
